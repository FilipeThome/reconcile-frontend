const catalogs: Record<AppLocale, Record<MessageKey, string>> = {
  'pt-BR': ptBR,
  'en-US': enUS,
}

let locale: AppLocale = readStored()
const listeners = new Set<() => void>()

function readStored(): AppLocale {
  if (typeof localStorage === 'undefined') return 'pt-BR'
  const stored = localStorage.getItem(STORAGE_KEY)
  return stored === 'en-US' ? 'en-US' : 'pt-BR'
}

export function getLocale(): AppLocale {
  return locale
}

export function setLocale(next: AppLocale) {
  locale = next
  if (typeof localStorage !== 'undefined') localStorage.setItem(STORAGE_KEY, next)
  if (typeof document !== 'undefined') document.documentElement.lang = next
  listeners.forEach((listener) => listener())
}

export function subscribeLocale(listener: () => void) {
  listeners.add(listener)
  return () => {
    listeners.delete(listener)
  }
}

export function t(key: MessageKey, vars?: Record<string, string | number>) {
  let text = catalogs[locale][key] ?? catalogs['pt-BR'][key]
  if (!vars) return text
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

export function labelOf(value: string) {
  const key = `status.${value}` as MessageKey
  if (key in catalogs['pt-BR']) return t(key)
  const method = `method.${value}` as MessageKey
  if (method in catalogs['pt-BR']) return t(method)
  const role = `role.${value.toLowerCase()}` as MessageKey
  if (role in catalogs['pt-BR']) return t(role)
  return value
}
